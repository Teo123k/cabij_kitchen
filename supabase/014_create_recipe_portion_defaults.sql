-- 014_create_recipe_portion_defaults.sql
-- Workflow-owned per-recipe portion baseline.
-- This table is additive and is intended to hold workflow-generated defaults,
-- not client-local overrides.

CREATE TABLE IF NOT EXISTS public.recipe_portion_defaults (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  recipe_ref_id TEXT NOT NULL,
  client_id TEXT,
  profile_version INTEGER NOT NULL DEFAULT 1,
  status TEXT NOT NULL DEFAULT 'active',
  default_portion_count NUMERIC,
  default_serving_size NUMERIC,
  default_serving_unit TEXT,
  default_portion_class TEXT,
  default_output_label TEXT,
  generated_by TEXT,
  generated_at TIMESTAMPTZ DEFAULT NOW(),
  source_note TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_recipe_portion_defaults_recipe_ref
  ON public.recipe_portion_defaults (recipe_ref_id);

CREATE INDEX IF NOT EXISTS idx_recipe_portion_defaults_client
  ON public.recipe_portion_defaults (client_id);

CREATE UNIQUE INDEX IF NOT EXISTS uq_recipe_portion_defaults_recipe_client_version
  ON public.recipe_portion_defaults (
    recipe_ref_id,
    COALESCE(client_id, '__global__'),
    profile_version
  );

COMMENT ON TABLE public.recipe_portion_defaults IS
  'Workflow-owned per-recipe portion and output defaults. Frontend may read this table, but client-local overrides belong in a separate override table.';

COMMENT ON COLUMN public.recipe_portion_defaults.client_id IS
  'Nullable tenant scope. NULL means the default is shared/global rather than client-specific.';

COMMENT ON COLUMN public.recipe_portion_defaults.default_portion_count IS
  'Workflow-generated default portion count baseline for the recipe.';

COMMENT ON COLUMN public.recipe_portion_defaults.default_serving_size IS
  'Workflow-generated default serving size baseline for the recipe.';

COMMENT ON COLUMN public.recipe_portion_defaults.default_serving_unit IS
  'Unit for the default serving size, such as g, ml, piece, or bowl.';

COMMENT ON COLUMN public.recipe_portion_defaults.default_portion_class IS
  'Workflow-generated portion class baseline, such as main, starter, side, component, or sauce.';

COMMENT ON COLUMN public.recipe_portion_defaults.default_output_label IS
  'Chef-readable output label generated by workflow logic, such as 10 portions or 2 trays.';
